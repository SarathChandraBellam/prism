"""Observability analytics over the trace dataset. No LLM, standard library only.

    python3 obs.py          # reads data/traces.jsonl, writes data/observability.md and data/obs.json

Answers: is the agent reliable, which models served it, how well are the MCP servers
and the skills used, and what does a verified answer cost.
"""
import collections, json, os, statistics, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, "data")
C = collections.Counter
out_lines = []


def P(s=""):
    out_lines.append(s); print(s)


def table(head, rows):
    P("| " + " | ".join(head) + " |"); P("|" + "---|" * len(head))
    for r in rows: P("| " + " | ".join(str(x) for x in r) + " |")
    P()


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "–"


def q(vals, p):
    vals = sorted(vals)
    return vals[min(int(len(vals) * p), len(vals) - 1)] if vals else 0


def prices():
    """List prices of the paid twins of the free models, for shadow costing. Cached in data/prices.json."""
    path = os.path.join(D, "prices.json")
    if not os.path.exists(path):
        d = json.load(urllib.request.urlopen("https://openrouter.ai/api/v1/models", timeout=60))["data"]
        json.dump({m["id"]: [float(m["pricing"]["prompt"]), float(m["pricing"]["completion"])] for m in d
                   if not m["id"].endswith(":free") and float(m["pricing"].get("prompt") or 0) > 0}, open(path, "w"))
    return json.load(open(path))


def load():
    spans = [json.loads(l) for l in open(os.path.join(D, "traces.jsonl"))]
    sc = {s["session_id"]: s for s in json.load(open(os.path.join(D, "scenarios.json")))}
    return spans, sc


def main():
    spans, sc = load()
    A = lambda s: s["attributes"]
    op = lambda s: A(s)["gen_ai.operation.name"]
    roots = [s for s in spans if op(s) == "invoke_agent"]
    chats = [s for s in spans if op(s) == "chat"]
    tools = [s for s in spans if op(s) == "execute_tool"]
    ok_chats = [s for s in chats if s["status"] == "ok"]
    by_trace = collections.defaultdict(list)
    for s in spans: by_trace[s["trace_id"]].append(s)
    conv = lambda s: A(s)["gen_ai.conversation.id"]
    res = {}

    # ---- shadow cost: tokens priced at the paid twin of the model that served the call
    pr = prices()
    twins = [pr[m[:-5]] for m in {A(s).get("gen_ai.response.model") for s in ok_chats} if m and m[:-5] in pr]
    fallback = [statistics.median(t[0] for t in twins), statistics.median(t[1] for t in twins)] if twins else [1.5e-7, 5e-7]
    priced = 0
    for s in chats:
        m = A(s).get("gen_ai.response.model") or ""
        p = pr.get(m[:-5] if m.endswith(":free") else m)
        priced += bool(p) and s["status"] == "ok"
        p = p or fallback
        s["shadow"] = (A(s).get("gen_ai.usage.input_tokens") or 0) * p[0] + (A(s).get("gen_ai.usage.output_tokens") or 0) * p[1]
    tin = sum(A(s).get("gen_ai.usage.input_tokens") or 0 for s in chats)
    tout = sum(A(s).get("gen_ai.usage.output_tokens") or 0 for s in chats)
    treason = sum(A(s).get("gen_ai.usage.reasoning_tokens") or 0 for s in chats)
    shadow = sum(s["shadow"] for s in chats)
    actual = sum(A(s).get("gen_ai.usage.cost") or 0 for s in chats)

    P("# Observability report (generated by obs.py)\n")
    P("## 1. Volume and reliability\n")
    checked = [r for r in roots if A(r)["eval.checks"]]
    passed = [r for r in checked if A(r)["eval.passed"] == A(r)["eval.checks"]]
    table(["Metric", "Value"], [
        ["Sessions / user turns (traces)", f"{len({conv(r) for r in roots})} / {len(roots)}"],
        ["Model requests (chat spans)", f"{len(chats)}, of which {len(chats) - len(ok_chats)} failed attempts ({pct(len(chats) - len(ok_chats), len(chats))})"],
        ["Tool calls (execute_tool spans)", f"{len(tools)}, of which {sum(t['status'] == 'error' for t in tools)} errors"],
        ["Turns that ended without an answer", f"{sum(r['status'] == 'error' for r in roots)} ({dict(C(A(r)['prism.stop_reason'] for r in roots if r['status'] == 'error'))})"],
        ["Model requests per turn (mean / max)", f"{len(chats) / len(roots):.1f} / {max(A(r)['prism.model_steps'] for r in roots)}"],
        ["Turn latency p50 / p95", f"{q([r['duration_ms'] for r in roots], .5) / 1000:.1f}s / {q([r['duration_ms'] for r in roots], .95) / 1000:.1f}s"],
        ["Model request latency p50 / p95", f"{q([s['duration_ms'] for s in ok_chats], .5) / 1000:.1f}s / {q([s['duration_ms'] for s in ok_chats], .95) / 1000:.1f}s"],
        ["Tokens in / out (reasoning)", f"{tin:,} / {tout:,} ({treason:,})"],
        ["Verifiable turns passed", f"{len(passed)} of {len(checked)} ({pct(len(passed), len(checked))})"],
    ])
    table(["Failed attempt type", "Count"], C(A(s).get("error.type") for s in chats if s["status"] == "error").most_common())

    # ---- models picked by the free router
    P("## 2. Models served by `openrouter/free`\n")
    final_model, tool_after = {}, collections.defaultdict(list)
    for tid, ss in by_trace.items():
        ss = sorted([s for s in ss if op(s) != "invoke_agent"], key=lambda s: s["start_time"])
        last = None
        for s in ss:
            if op(s) == "chat" and s["status"] == "ok": last = A(s)["gen_ai.response.model"]
            elif op(s) == "execute_tool" and last: tool_after[last].append(s)
        final_model[tid] = last
    rows = []
    for m, n in C(A(s)["gen_ai.response.model"] for s in ok_chats).most_common():
        cs = [s for s in ok_chats if A(s)["gen_ai.response.model"] == m]
        ta = tool_after[m]
        bad = sum(A(t).get("error.type") in ("bad_arguments", "unknown_tool", "unknown_skill") for t in ta)
        fin = [r for r in checked if final_model.get(r["trace_id"]) == m]
        fp = sum(A(r)["eval.passed"] == A(r)["eval.checks"] for r in fin)
        rows.append([m, n, pct(n, len(ok_chats)), f"{q([s['duration_ms'] for s in cs], .5) / 1000:.1f}s",
                     int(statistics.mean(A(s).get("gen_ai.usage.output_tokens") or 0 for s in cs)),
                     len(ta), f"{sum(t['status'] == 'error' for t in ta)} ({bad} malformed)", f"{fp}/{len(fin)}"])
    table(["Served model", "Calls", "Share", "p50 latency", "Mean out tokens", "Tool calls issued", "Tool errors", "Final answers passing checks"], rows)
    res["models"] = len(rows)

    # ---- MCP servers
    P("## 3. MCP usage\n")
    schema = A(chats[0])["prism.tool_schema_chars"]
    in_chars = sum(A(s)["prism.input_chars"] + sum(A(s)["prism.tool_schema_chars"].values()) for s in ok_chats)
    schema_tok = {k: sum(A(s)["prism.tool_schema_chars"][k] for s in ok_chats) / in_chars * sum(A(s).get("gen_ai.usage.input_tokens") or 0 for s in ok_chats)
                  for k in schema}
    in_ok = sum(A(s).get("gen_ai.usage.input_tokens") or 0 for s in ok_chats)
    spans_sess = collections.defaultdict(list)
    for t in tools: spans_sess[conv(t)].append(t)
    offered_n = {"shop": 5, "filesystem": 14, "memory": 9}
    known = {"shop", "filesystem", "memory"}
    for t in tools:                      # a call with unparseable arguments never reached a server: attribute it by name
        if not A(t).get("mcp.server.name") and A(t)["gen_ai.tool.name"].split("__")[0] in known:
            A(t)["mcp.server.name"] = A(t)["gen_ai.tool.name"].split("__")[0]
    rows, per_tool = [], C((A(t).get("mcp.server.name"), A(t)["gen_ai.tool.name"]) for t in tools)
    for srv in ("shop", "filesystem", "memory"):
        ts = [t for t in tools if A(t).get("mcp.server.name") == srv]
        used = {A(t)["gen_ai.tool.name"] for t in ts}
        want = [s for s in {conv(r) for r in roots} if srv in sc[s]["designed"]["servers"]]
        got = [s for s in want if any(A(t).get("mcp.server.name") == srv for t in spans_sess[s])]
        sess_used = {conv(t) for t in ts}
        rows.append([srv, offered_n[srv], len(used), len(ts), pct(sum(t["status"] == "error" for t in ts), len(ts)),
                     f"{q([t['duration_ms'] for t in ts], .5)}ms", f"{len(sess_used)}", f"{len(got)}/{len(want)}",
                     f"{schema_tok[srv]:,.0f} ({pct(schema_tok[srv], in_ok)})",
                     f"{schema_tok[srv] / len(ts):,.0f}" if ts else "∞"])
    table(["Server", "Tools offered", "Tools used", "Calls", "Error rate", "p50 latency", "Sessions using it",
           "Used where designed", "Schema tokens sent (share of all input)", "Schema tokens per call made"], rows)
    table(["Tool", "Calls", "Errors"], [[n if srv else n + " (not a real tool)", c, sum(t["status"] == "error" for t in tools if A(t)["gen_ai.tool.name"] == n)]
                                        for (srv, n), c in per_tool.most_common() if srv != "skill"])
    errs = C((A(t)["gen_ai.tool.name"], A(t).get("error.type"), A(t)["gen_ai.tool.call.result"][:90].replace("\n", " ").replace("|", "/")) for t in tools if t["status"] == "error")
    if errs:
        P("Most common tool errors:\n")
        table(["Tool", "Type", "Message", "Count"], [[a, b, c, n] for (a, b, c), n in errs.most_common(8)])
    res["schema_share"] = sum(v for k, v in schema_tok.items() if k != "skill") / in_ok

    # ---- skills
    P("## 4. Skill usage\n")
    loads = collections.defaultdict(C)
    for t in tools:
        if A(t)["gen_ai.tool.name"] == "load_skill": loads[conv(t)][A(t).get("prism.skill.name")] += 1
    run_sessions = {conv(r) for r in roots}
    names = sorted({v["designed"]["skill"] for v in sc.values() if v["designed"]["skill"]} | {k for c in loads.values() for k in c if k})
    rows = []
    for n in names:
        exp = {s for s in run_sessions if sc[s]["designed"]["skill"] == n}
        got = {s for s in run_sessions if loads[s][n]}
        rows.append([n, len(exp), len(got), f"{len(exp & got)}/{len(exp)}", f"{len(exp & got)}/{len(got)}" if got else "–",
                     sum(loads[s][n] for s in got), sum(loads[s][n] - 1 for s in got)])
    table(["Skill", "Sessions designed for it", "Sessions that loaded it", "Recall", "Precision", "Loads", "Repeat loads in a session"], rows)
    P("Precision is against the session's *main* designed skill, so a justified secondary load (a reply drafted after a refund check) counts against it.\n")

    def rate(rs):
        rs = [r for r in rs if A(r)["eval.checks"]]
        return f"{pct(sum(A(r)['eval.passed'] == A(r)['eval.checks'] for r in rs), len(rs))} (n={len(rs)})"
    with_skill = [r for r in roots if sc[conv(r)]["designed"]["skill"] and loads[conv(r)][sc[conv(r)]["designed"]["skill"]]]
    without = [r for r in roots if sc[conv(r)]["designed"]["skill"] and not loads[conv(r)][sc[conv(r)]["designed"]["skill"]]]
    noskill = [r for r in roots if not sc[conv(r)]["designed"]["skill"]]
    table(["Turns in sessions where…", "Verifiable turns passed"], [
        ["a skill applies and it was loaded", rate(with_skill)],
        ["a skill applies and it was NOT loaded", rate(without)],
        ["no skill applies", rate(noskill)]])
    first_turn_load = sum(1 for s in run_sessions if sc[s]["designed"]["skill"] and any(
        A(t)["gen_ai.tool.name"] == "load_skill" and A(t).get("prism.skill.name") == sc[s]["designed"]["skill"] and
        t["trace_id"] == min((r for r in roots if conv(r) == s), key=lambda r: A(r)["prism.turn_index"])["trace_id"] for t in spans_sess[s]))
    P(f"Designed skill loaded already in the first turn: {first_turn_load} of {sum(1 for s in run_sessions if sc[s]['designed']['skill'])} sessions.\n")

    # ---- quality by slice
    P("## 5. Answer quality by slice\n")
    def slice_(key):
        g = collections.defaultdict(list)
        for r in roots: g[key(r)].append(r)
        return [[k, len(v), rate(v), f"${sum(s['shadow'] for t in v for s in by_trace[t['trace_id']] if op(s) == 'chat') / len(v) * 1000:.3f}"] for k, v in sorted(g.items())]
    table(["Task type", "Turns", "Verifiable turns passed", "Shadow cost per 1,000 turns"], slice_(lambda r: sc[conv(r)]["designed"]["task_type"]))
    table(["Person", "Turns", "Verifiable turns passed", "Shadow cost per 1,000 turns"], slice_(lambda r: A(r)["user.id"]))
    table(["Turn act", "Turns", "Verifiable turns passed", "Shadow cost per 1,000 turns"],
          slice_(lambda r: sc[conv(r)]["turns"][A(r)["prism.turn_index"] - 1]["act"]))
    table(["Turn position", "Turns", "Verifiable turns passed", "Shadow cost per 1,000 turns"],
          slice_(lambda r: f"turn {min(A(r)['prism.turn_index'], 4)}{'+' if A(r)['prism.turn_index'] >= 4 else ''}"))
    table(["Failed check kind", "Failed", "Total"], [[k, f, t] for k, (f, t) in sorted(
        {k: (sum(1 for r in roots for d in A(r)["eval.detail"] if d["check"] == k and not d["ok"]),
             sum(1 for r in roots for d in A(r)["eval.detail"] if d["check"] == k)) for k in
         {d["check"] for r in roots for d in A(r)["eval.detail"]}}.items())])

    # ---- value for money
    P("## 6. Value for money\n")
    waste_fail = sum(s["shadow"] for s in chats if s["status"] == "error")
    cost_trace = {tid: sum(s["shadow"] for s in ss if op(s) == "chat") for tid, ss in by_trace.items()}
    cost_failed_checks = sum(cost_trace[r["trace_id"]] for r in checked if r not in passed)
    sys_tok = in_ok - sum(schema_tok.values())
    table(["Metric", "Value"], [
        ["Actual spend (free models)", f"${actual:.4f}"],
        ["Shadow cost at paid list prices", f"${shadow:.4f} ({priced} of {len(ok_chats)} answered calls priced by their own paid twin, the rest at the median twin price)"],
        ["Shadow cost per session / per turn", f"${shadow / len({conv(r) for r in roots}):.5f} / ${shadow / len(roots):.5f}"],
        ["Shadow cost per verified-correct turn", f"${sum(cost_trace[r['trace_id']] for r in checked) / max(len(passed), 1):.5f}"],
        ["Share of shadow cost on turns that failed their checks", pct(cost_failed_checks, sum(cost_trace[r['trace_id']] for r in checked))],
        ["Input tokens per turn (mean)", f"{tin / len(roots):,.0f}"],
        ["Input tokens that are MCP tool schemas", f"{pct(sum(v for k, v in schema_tok.items() if k != 'skill'), in_ok)}"],
        ["Input tokens saved if servers with no calls in a session were not attached to it", pct(sum(
            A(s)["prism.tool_schema_chars"][k] for s in ok_chats for k in ("shop", "filesystem", "memory")
            if not any(A(t).get("mcp.server.name") == k for t in spans_sess[conv(s)])) / in_chars * in_ok, in_ok)],
        ["Input share of total shadow cost", pct(sum((A(s).get('gen_ai.usage.input_tokens') or 0) * (pr.get((A(s).get('gen_ai.response.model') or '')[:-5]) or fallback)[0] for s in chats), shadow)],
        ["Prompt-cache hits (cached input tokens)", f"{sum(A(s).get('gen_ai.usage.cached_tokens') or 0 for s in chats):,} of {tin:,}"],
    ])
    growth = collections.defaultdict(list)
    for r in roots:
        cs = [s for s in by_trace[r["trace_id"]] if op(s) == "chat" and s["status"] == "ok"]
        if cs: growth[min(A(r)["prism.turn_index"], 4)].append(statistics.mean(A(s).get("gen_ai.usage.input_tokens") or 0 for s in cs))
    table(["Turn in session", "Mean input tokens per model request"], [[f"{k}{'+' if k == 4 else ''}", f"{statistics.mean(v):,.0f}"] for k, v in sorted(growth.items())])

    abl = os.path.join(D, "traces-noskill.jsonl")
    if os.path.exists(abl):
        P("## 7. Ablation: the same sessions without skills\n")
        other = [json.loads(l) for l in open(abl)]
        oroots = {(conv(s), A(s)["prism.turn_index"]): s for s in other if op(s) == "invoke_agent"}
        ochat = collections.defaultdict(list)
        for s in other:
            if op(s) == "chat": ochat[s["trace_id"]].append(s)
        def arm(rs, chat_of):
            ch = [r for r in rs if A(r)["eval.checks"]]
            cs = [c for r in rs for c in chat_of(r)]
            cost = 0
            for c in cs:
                m = A(c).get("gen_ai.response.model") or ""
                p = pr.get(m[:-5] if m.endswith(":free") else m) or fallback
                cost += (A(c).get("gen_ai.usage.input_tokens") or 0) * p[0] + (A(c).get("gen_ai.usage.output_tokens") or 0) * p[1]
            ok = sum(A(r)["eval.passed"] == A(r)["eval.checks"] for r in ch)
            return [len(rs), f"{ok}/{len(ch)} ({pct(ok, len(ch))})", f"{len(cs) / len(rs):.1f}",
                    f"{sum(A(c).get('gen_ai.usage.input_tokens') or 0 for c in cs) / len(rs):,.0f}", f"${cost / len(rs) * 1000:.3f}",
                    f"${cost / max(ok, 1) * 1000:.3f}"]
        rows = []
        groups = [("all paired turns", lambda r: True)] + [(f"skill: {n}", lambda r, n=n: sc[conv(r)]["designed"]["skill"] == n) for n in names] + \
                 [("no skill designed", lambda r: not sc[conv(r)]["designed"]["skill"]),
                  ("skill designed, outcome checks only (numbers, database state, files)", lambda r: sc[conv(r)]["designed"]["skill"] and A(r)["eval.detail"]
                   and all(d["check"] in ("num", "ticket", "tickets", "note", "file") for d in A(r)["eval.detail"]))]
        for label, f in groups:
            base = [r for r in roots if (conv(r), A(r)["prism.turn_index"]) in oroots and f(r)]
            if not base: continue
            rows.append([label, "with skills"] + arm(base, lambda r: [s for s in by_trace[r["trace_id"]] if op(s) == "chat"]))
            rows.append(["", "without"] + arm([oroots[(conv(r), A(r)["prism.turn_index"])] for r in base], lambda r: ochat[r["trace_id"]]))
        table(["Turns", "Arm", "n", "Verifiable turns passed", "Model calls per turn", "Input tokens per turn", "Shadow cost per 1,000 turns", "Shadow cost per 1,000 verified-correct turns"], rows)

    res.update({"turns": len(roots), "chats": len(chats), "tool_calls": len(tools), "tokens_in": tin, "tokens_out": tout,
                "shadow_usd": shadow, "actual_usd": actual, "pass": len(passed), "checked": len(checked)})
    json.dump(res, open(os.path.join(D, "obs.json"), "w"), indent=1)
    open(os.path.join(D, "observability.md"), "w").write("\n".join(out_lines) + "\n")


if __name__ == "__main__":
    main()
